const { chromium } = require('playwright');
(async() => {
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage();
  const logs = [];
  page.on('console', msg => logs.push(`console:${msg.type()}:${msg.text()}`));
  page.on('pageerror', err => logs.push(`pageerror:${err.message}`));
  page.on('requestfailed', req => logs.push(`requestfailed:${req.url()} ${req.failure()?.errorText || ''}`));
  await page.goto('http://127.0.0.1:4173/', { waitUntil: 'networkidle' });
  const title = await page.textContent('.title');
  const before = await page.locator('.nav-link.active').textContent();
  await page.getByRole('button', { name: '个人中心' }).click();
  await page.waitForTimeout(300);
  const modalVisible = await page.locator('.modal-overlay').isVisible().catch(() => false);
  const meActive = await page.locator('.nav-link.active').textContent().catch(() => null);
  await page.getByRole('button', { name: '登录' }).click().catch(() => {});
  await page.waitForTimeout(200);
  const loginModalVisible = await page.locator('.modal-overlay').isVisible().catch(() => false);
  console.log(JSON.stringify({title, before, modalVisible, meActive, loginModalVisible, logs}, null, 2));
  await browser.close();
})();